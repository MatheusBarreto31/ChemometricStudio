                            _meta['ga_max_evaluations'] = int(ga_max_evaluations)
                            _meta['ga_min_improvement'] = float(ga_min_improvement)
                            _meta['ga_evaluations_used'] = int(ga_evaluations)
                            _meta['ga_random_state'] = int(ga_random_state)
