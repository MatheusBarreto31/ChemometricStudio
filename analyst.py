    workspace_root = os.path.dirname(os.path.abspath(__file__))

    def _resolve_model_json_path() -> Path:
        env_path = os.environ.get("CMSTUDIO_MODEL_JSON_PATH", "").strip()
        if env_path:
            candidate = Path(env_path)
            if candidate.exists():
                return candidate

        return get_runtime_model_json_path()

    model_json_path = _resolve_model_json_path()

    # Load model configuration from model.json
    if not os.path.exists(model_json_path):
        raise FileNotFoundError(
            f"model.json not found at {model_json_path}. This indicates a serious error: the model was not generated by the GUI. Please re-run the GUI to generate a valid model.json."
        )
    with open(model_json_path, 'r', encoding='utf-8-sig') as f:
        model_data = json.load(f)

    # Load merged specs (core + available add-ons) using the active app language.
    settings_manager = get_settings_manager()
    active_language = str(settings_manager.get("language", "en") or "en")
    combined_specs_payload = load_combined_function_specs(Path(workspace_root), language=active_language)
    specs_data = combined_specs_payload['specs']
    addon_registry = combined_specs_payload.get('addon_registry', {})

    required_addons = normalize_required_addons(model_data.get('metadata', {}).get('required_addons', []))
    available_addons = set(addon_registry.get('available_addons', {}).keys())
    missing_addons = [addon_id for addon_id in required_addons if addon_id not in available_addons]
    if missing_addons:
        raise RuntimeError(
            "Model requires missing add-ons: " + ", ".join(missing_addons)
        )

    available_aliases = set(specs_data.get('gui_listing', {}).keys())
    model_aliases = {
        str(entry.get('base_alias', ''))
        for entry in model_data.get('functions', [])
        if isinstance(entry, dict)
    }
    missing_aliases = sorted(alias for alias in model_aliases if alias and alias not in available_aliases)
    if missing_aliases:
        raise RuntimeError(
            "Model references unavailable functions: " + ", ".join(missing_aliases)
        )
    
    return_specs = specs_data['return_specs']
    input_specs = specs_data['input_specs']

    def _load_addon_attr(addon_id: str, module_name: str, attr_name: str):
        """Load an add-on attribute from the add-on's own chemometrics tree without global namespace clashes."""
        addon_meta = addon_registry.get('available_addons', {}).get(addon_id, {})
        addon_root = addon_meta.get('root_path')
        if not addon_root:
            raise ModuleNotFoundError(f"Add-on '{addon_id}' is not available")

        if not module_name.startswith('chemometrics'):
            module = importlib.import_module(module_name)
            return getattr(module, attr_name)

        suffix = module_name[len('chemometrics'):].lstrip('.')
        suffix_parts = suffix.split('.') if suffix else []
        base_path = Path(addon_root) / 'chemometrics'

        module_file = base_path.joinpath(*suffix_parts).with_suffix('.py') if suffix_parts else (base_path / '__init__.py')
        if not module_file.exists():
            module_file = base_path.joinpath(*suffix_parts) / '__init__.py' if suffix_parts else (base_path / '__init__.py')
        if not module_file.exists():
            raise ModuleNotFoundError(
                f"Module '{module_name}' for add-on '{addon_id}' was not found"
            )

        safe_addon = addon_id.replace('-', '_').replace(' ', '_')
        safe_suffix = '__'.join(suffix_parts) if suffix_parts else 'root'
        synthetic_name = f"_cmstudio_addons.{safe_addon}.{safe_suffix}"

        if synthetic_name in globals():
            module = globals()[synthetic_name]
        else:
            spec = importlib.util.spec_from_file_location(synthetic_name, str(module_file))
            if spec is None or spec.loader is None:
                raise ImportError(f"Cannot create import spec for '{module_file}'")
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            globals()[synthetic_name] = module

        if not hasattr(module, attr_name):
            raise AttributeError(
                f"Module '{module_name}' in add-on '{addon_id}' does not define '{attr_name}'"
            )
        return getattr(module, attr_name)

    def _resolve_gui_config_path(config_path: str) -> Optional[str]:
        """Resolve GUI config path with an English fallback for analyst-mode execution."""
        if not config_path:
            return None

        normalized = str(config_path).replace('\\\\', os.sep).replace('/', os.sep)
        candidates = [normalized]

        # Backward compatibility: specs may omit language folder (e.g., gui_configs/<file>.json).
        if normalized.startswith(f"gui_configs{os.sep}"):
            filename = os.path.basename(normalized)
            candidates.append(os.path.join('gui_configs', active_language, filename))
            candidates.append(os.path.join('gui_configs', 'en', filename))

        for candidate in candidates:
            absolute_candidate = candidate if os.path.isabs(candidate) else os.path.join(workspace_root, candidate)
            if os.path.exists(absolute_candidate):
                return absolute_candidate
        return None

    def _coerce_bool(value: Any) -> bool:
        """Parse booleans safely from mixed model/JSON values."""
        if isinstance(value, bool):
            return value
        if isinstance(value, (int, float)):
            return value != 0
        if isinstance(value, str):
            normalized = value.strip().lower()
            if normalized in {"true", "1", "yes", "y", "on"}:
                return True
            if normalized in {"false", "0", "no", "n", "off", ""}:
                return False
        return bool(value)

    def _build_function_default_params(spec_data: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
        """Build {base_alias: {param_name: default_value}} from GUI config files."""
        defaults_by_function: Dict[str, Dict[str, Any]] = {}
        gui_listing = spec_data.get('gui_listing', {})
        if not isinstance(gui_listing, dict):
            return defaults_by_function

        for base_alias, gui_meta in gui_listing.items():
            if not isinstance(gui_meta, dict):
                continue
            config_path = _resolve_gui_config_path(gui_meta.get('config_path', ''))
            if not config_path:
                continue

            try:
                with open(config_path, 'r', encoding='utf-8-sig') as config_file:
                    config_data = json.load(config_file)
            except Exception:
                continue

            layout = config_data.get('setup', {}).get('layout', [])
            if not isinstance(layout, list):
                continue

            function_defaults: Dict[str, Any] = {}
            for field in layout:
                if not isinstance(field, dict):
                    continue
                param_name = field.get('name')
                if not param_name or 'default' not in field:
                    continue
                function_defaults[param_name] = field.get('default')

            if function_defaults:
                defaults_by_function[base_alias] = function_defaults

        return defaults_by_function

    def _build_function_translation_keys(spec_data: Dict[str, Any]) -> Dict[str, Dict[str, str]]:
        """Build {base_alias: translation_keys_dict} from GUI config files."""
        keys_by_function: Dict[str, Dict[str, str]] = {}
        gui_listing = spec_data.get('gui_listing', {})
        if not isinstance(gui_listing, dict):
            return keys_by_function

        for base_alias, gui_meta in gui_listing.items():
            if not isinstance(gui_meta, dict):
                continue
            config_path = _resolve_gui_config_path(gui_meta.get('config_path', ''))
            if not config_path:
                continue

            try:
                with open(config_path, 'r', encoding='utf-8-sig') as config_file:
                    config_data = json.load(config_file)
            except Exception:
                continue

            translation_keys = config_data.get('translation_keys')
            if isinstance(translation_keys, dict):
                keys_by_function[base_alias] = translation_keys

        return keys_by_function

    def _build_function_passforward_specs(spec_data: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
        """Build {base_alias: passforward_spec} from GUI config files."""
        passforward_by_function: Dict[str, Dict[str, Any]] = {}
        gui_listing = spec_data.get('gui_listing', {})
        if not isinstance(gui_listing, dict):
            return passforward_by_function

        for base_alias, gui_meta in gui_listing.items():
            if not isinstance(gui_meta, dict):
                continue
            config_path = _resolve_gui_config_path(gui_meta.get('config_path', ''))
            if not config_path:
                continue

            try:
                with open(config_path, 'r', encoding='utf-8-sig') as config_file:
                    config_data = json.load(config_file)
            except Exception:
                continue

            raw_pf = config_data.get('passforward')
            if not isinstance(raw_pf, dict) or not bool(raw_pf.get('compatible', False)):
                continue

            raw_mappings = raw_pf.get('mappings', {})
            if not isinstance(raw_mappings, dict):
                continue

            normalized_mappings: Dict[str, Dict[str, str]] = {}
            for dst_key, mapping in raw_mappings.items():
                if not isinstance(dst_key, str) or not dst_key.strip():
                    continue

                source_key = ''
                nested_key = ''
                has_constant = False
                constant_value: Any = None
                builder = ''

                if isinstance(mapping, str):
                    source_key = mapping.strip()
                elif isinstance(mapping, dict):
                    source_key = str(mapping.get('source', '') or mapping.get('src_key', '')).strip()
                    nested_key = str(mapping.get('nested_key', '') or '').strip()
                    builder = str(mapping.get('builder', '') or '').strip()
                    if 'value' in mapping:
                        has_constant = True
                        constant_value = mapping.get('value')

                if not source_key and not has_constant and not builder:
                    continue

                normalized_mapping: Dict[str, Any] = {
                    'source': source_key,
                    'nested_key': nested_key,
                }
                if has_constant:
                    normalized_mapping['value'] = constant_value
                if builder:
                    normalized_mapping['builder'] = builder
                if isinstance(mapping, dict):
                    for extra_key, extra_value in mapping.items():
                        if extra_key in normalized_mapping:
                            continue
                        normalized_mapping[extra_key] = extra_value

                normalized_mappings[dst_key.strip()] = normalized_mapping

            if normalized_mappings:
                passforward_by_function[base_alias] = {
                    'mappings': normalized_mappings,
                }

        return passforward_by_function

    def _build_function_input_types(spec_data: Dict[str, Any]) -> Dict[str, Dict[str, str]]:
        """Build {base_alias: {param_name: input_type}} from GUI config files."""
        input_types_by_function: Dict[str, Dict[str, str]] = {}
        gui_listing = spec_data.get('gui_listing', {})
        if not isinstance(gui_listing, dict):
            return input_types_by_function

        for base_alias, gui_meta in gui_listing.items():
            if not isinstance(gui_meta, dict):
                continue
            config_path = _resolve_gui_config_path(gui_meta.get('config_path', ''))
            if not config_path:
                continue

            try:
                with open(config_path, 'r', encoding='utf-8-sig') as config_file:
                    config_data = json.load(config_file)
            except Exception:
                continue

            layout = config_data.get('setup', {}).get('layout', [])
            if not isinstance(layout, list):
                continue

            function_input_types: Dict[str, str] = {}
            for field in layout:
                if not isinstance(field, dict):
                    continue
                param_name = field.get('name')
                if not isinstance(param_name, str) or not param_name:
                    continue
                raw_input_type = str(field.get('input_type', '') or '').strip().lower()
                if raw_input_type in {'user', 'routed', 'inherited'}:
                    function_input_types[param_name] = raw_input_type

            if function_input_types:
                input_types_by_function[base_alias] = function_input_types

        return input_types_by_function

    function_default_params = _build_function_default_params(specs_data)
    function_translation_keys = _build_function_translation_keys(specs_data)
    function_passforward_specs = _build_function_passforward_specs(specs_data)
    function_input_types = _build_function_input_types(specs_data)
    
    # Convert import_map tuples back from list format
    import_map = {}
    for func_name, import_info in specs_data['import_map'].items():
        import_map[func_name] = tuple(import_info)
    
    workflow_control_aliases = {
        "workflow_loop_start",
        "workflow_loop_end",
        "workflow_parallel_start",
        "workflow_parallel_branch",
        "workflow_parallel_end",
        "workflow_ensemble_start",
        "workflow_ensemble_member",
        "workflow_ensemble_end",
        "workflow_variable_selection_start",
        "workflow_variable_selection_end",
    }

    # Extract function information from model
    functions_info = {}  # {instance_alias: {base_alias, parameters, parameter_types}}
    functions_list = []
    for func_entry in model_data.get('functions', []):
        instance_alias = func_entry.get('instance_alias', '')
        base_alias = func_entry.get('base_alias', '')
        saved_params = func_entry.get('parameters', {})
        params = saved_params.copy() if isinstance(saved_params, dict) else {}
        legacy_passforward_enabled = _coerce_bool(params.pop('__passforward_enabled__', False))
        passforward_entry = func_entry.get('passforward', {})
        # Explicit per-function setting takes precedence; legacy field is fallback only.
        if isinstance(passforward_entry, dict) and 'enabled' in passforward_entry:
            passforward_enabled = _coerce_bool(passforward_entry.get('enabled', False))
        else:
            passforward_enabled = legacy_passforward_enabled
        param_types = func_entry.get('parameter_types', {})
        
        functions_info[instance_alias] = {
            'base_alias': base_alias,
            'parameters': params,
            'parameter_types': param_types,
            'passforward_enabled': passforward_enabled,
        }
        functions_list.append({
            'model_idx': len(functions_list),
            'instance_alias': instance_alias,
            'base_alias': base_alias
        })
    
    # Extract routing information from model
    routing_map = {}  # {dst_instance: {dst_param: [source_mappings...]}}
    for route_entry in model_data.get('routing', []):
        src_info = route_entry.get('source', {})
        dst_info = route_entry.get('destination', {})
        
        src_alias = src_info.get('instance_alias', '')
        dst_alias = dst_info.get('instance_alias', '')
        src_param = src_info.get('param_key', '')
        src_nested_key = src_info.get('nested_key', '')
        dst_param = dst_info.get('param_key', '')
        
        if dst_alias not in routing_map:
            routing_map[dst_alias] = {}
        if dst_param not in routing_map[dst_alias]:
            routing_map[dst_alias][dst_param] = []
        routing_map[dst_alias][dst_param].append({
            'src_alias': src_alias,
            'src_param': src_param,
            'src_nested_key': src_nested_key
        })
    
    # Collect unique functions and import them
    unique_funcs = set()
    for instance_alias, info in functions_info.items():
        base_alias = info['base_alias']
        unique_funcs.add(base_alias)
    
    executed_steps = 0
    total_functions = len(functions_list)
    if stop_at_function_idx is not None:
        function_execution_target = min(total_functions, max(0, stop_at_function_idx + 1))
    else:
        function_execution_target = total_functions

    def _find_matching_end_static(start_idx: int, start_alias: str, end_alias: str) -> int:
        depth = 0
        for i in range(start_idx + 1, len(functions_list)):
            alias = functions_list[i]['base_alias']
            if alias == start_alias:
                depth += 1
            elif alias == end_alias:
                if depth == 0:
                    return i
                depth -= 1
        return -1

    def _resolve_loop_iterations_for_progress(loop_params: Dict[str, Any]) -> int:
        try:
            iterations = int(loop_params.get('iterations', 1))
        except Exception:
            iterations = 1
        iterations = max(1, iterations)

        loop_mode = str(loop_params.get('mode', 'repeat') or 'repeat')
        sweep_values = _parse_sweep_values(loop_params.get('sweep_values', ''))
        if loop_mode == "sweep_choice":
            sweep_choice_values = loop_params.get('sweep_choice_values', [])
            if isinstance(sweep_choice_values, str):
                sweep_choice_values = [part.strip() for part in sweep_choice_values.split(',') if part.strip()]
            if isinstance(sweep_choice_values, list) and sweep_choice_values:
                sweep_values = [str(v) for v in sweep_choice_values]

        if loop_mode in ("sweep_numeric", "sweep_choice") and sweep_values:
            iterations = len(sweep_values)

        return max(1, int(iterations))

    def _estimate_progress_steps(start_idx: int, end_idx: int) -> int:
        total_steps = 0
        idx = start_idx

        while idx <= end_idx and idx < len(functions_list):
            entry = functions_list[idx]
            base_alias = entry['base_alias']
            model_idx = entry['model_idx']

            if stop_at_function_idx is not None and model_idx > stop_at_function_idx:
                return total_steps

            if base_alias == "workflow_loop_start":
                loop_end_idx = _find_matching_end_static(idx, "workflow_loop_start", "workflow_loop_end")
                total_steps += 1
                if loop_end_idx < 0:
                    idx += 1
                    continue

                body_start = idx + 1
                body_end = loop_end_idx - 1
                if body_start <= body_end:
                    loop_instance_alias = entry['instance_alias']
                    loop_info = functions_info.get(loop_instance_alias, {})
                    loop_params = loop_info.get('parameters', {})
                    iterations = _resolve_loop_iterations_for_progress(loop_params)
                    body_steps = _estimate_progress_steps(body_start, body_end)
                    total_steps += iterations * body_steps

                idx = loop_end_idx + 1
                continue

            if base_alias == "workflow_variable_selection_start":
                selection_end_idx = _find_matching_end_static(
                    idx,
                    "workflow_variable_selection_start",
                    "workflow_variable_selection_end",
                )
                total_steps += 1
                if selection_end_idx < 0:
                    idx += 1
                    continue

                body_start = idx + 1
                body_end = selection_end_idx - 1

                if body_start > body_end:
                    raise ValueError(
                        "workflow_variable_selection_start requires at least one enclosed function before workflow_variable_selection_end."
                    )
                if body_start <= body_end:
                    total_steps += _estimate_progress_steps(body_start, body_end)

                idx = selection_end_idx + 1
                continue

            if base_alias == "workflow_parallel_start":
                parallel_end_idx = _find_matching_end_static(idx, "workflow_parallel_start", "workflow_parallel_end")
                total_steps += 1
                if parallel_end_idx < 0:
                    idx += 1
                    continue

                block_start = idx + 1
                block_end = parallel_end_idx - 1
                if block_start <= block_end:
                    branch_ranges: List[Tuple[int, int]] = []
                    branch_start = block_start
                    nested_parallel_depth = 0
                    for branch_idx in range(block_start, block_end + 1):
                        branch_alias = functions_list[branch_idx]['base_alias']
                        if branch_alias == "workflow_parallel_start":
                            nested_parallel_depth += 1
                        elif branch_alias == "workflow_parallel_end" and nested_parallel_depth > 0:
                            nested_parallel_depth -= 1
                        elif branch_alias == "workflow_parallel_branch" and nested_parallel_depth == 0:
                            if branch_start <= branch_idx - 1:
                                branch_ranges.append((branch_start, branch_idx - 1))
                            branch_start = branch_idx + 1
                    if branch_start <= block_end:
                        branch_ranges.append((branch_start, block_end))

                    for range_start, range_end in branch_ranges:
                        total_steps += _estimate_progress_steps(range_start, range_end)

                idx = parallel_end_idx + 1
                continue

            if base_alias == "workflow_ensemble_start":
                ensemble_end_idx = _find_matching_end_static(idx, "workflow_ensemble_start", "workflow_ensemble_end")
                total_steps += 1
                if ensemble_end_idx < 0:
                    idx += 1
                    continue

                block_start = idx + 1
                block_end = ensemble_end_idx - 1
                if block_start <= block_end:
                    member_ranges: List[Tuple[int, int]] = []
                    member_start = block_start
                    nested_ensemble_depth = 0
                    for member_idx in range(block_start, block_end + 1):
                        member_alias = functions_list[member_idx]['base_alias']
                        if member_alias == "workflow_ensemble_start":
                            nested_ensemble_depth += 1
                        elif member_alias == "workflow_ensemble_end" and nested_ensemble_depth > 0:
                            nested_ensemble_depth -= 1
                        elif member_alias == "workflow_ensemble_member" and nested_ensemble_depth == 0:
                            if member_start <= member_idx - 1:
                                member_ranges.append((member_start, member_idx - 1))
                            member_start = member_idx + 1
                    if member_start <= block_end:
                        member_ranges.append((member_start, block_end))

                    for range_start, range_end in member_ranges:
                        total_steps += _estimate_progress_steps(range_start, range_end)

                idx = ensemble_end_idx + 1
                continue

            if base_alias in (
                "workflow_loop_end",
                "workflow_parallel_branch",
                "workflow_parallel_end",
                "workflow_ensemble_member",
                "workflow_ensemble_end",
                "workflow_variable_selection_end",
            ):
                idx += 1
                continue

            total_steps += 1
            idx += 1

        return total_steps

    progress_total = _estimate_progress_steps(0, len(functions_list) - 1) + 1

    if progress_callback:
        try:
            progress_callback(executed_steps, progress_total, "", "__lazy_loading__")
        except Exception:
            pass

    lazy_loading_start_time = perf_counter()
    for func in unique_funcs:
        if func in workflow_control_aliases:
            continue
        if func in import_map:
            module_name, attr_name = import_map[func]
            addon_id = addon_registry.get('function_to_addon', {}).get(func)
            if addon_id:
                globals()[func] = _load_addon_attr(addon_id, module_name, attr_name)
            else:
                module = importlib.import_module(module_name)
                globals()[func] = getattr(module, attr_name)
    lazy_loading_elapsed_seconds = perf_counter() - lazy_loading_start_time

    executed_steps = 1
    if progress_callback:
        try:
            progress_callback(executed_steps, progress_total, "", "__lazy_loading__")
        except Exception:
            pass

    pipeline_start_time = perf_counter()
    
    def _convert_param_types(base_alias, param_name, value, type_info):
        """Convert a parameter value to its specified type."""
        if value is None:
            return None
        
        param_type = type_info.get(param_name, "str")
        
        if param_type == "int":
            if isinstance(value, str):
                return int(value)
            elif isinstance(value, (int, float)):
                return int(value)
            else:
                return value
        elif param_type == "float":
            if isinstance(value, str):
                return float(value)
            elif isinstance(value, (int, float)):
                return float(value)
            else:
                return value
        elif param_type == "bool":
            if isinstance(value, bool):
                return value
            elif isinstance(value, str):
                return value.lower() in ('true', '1', 'yes')
            else:
                return bool(value)
        elif param_type == "list":
            if isinstance(value, list):
                return value
            elif isinstance(value, str):
                try:
                    parsed = ast.literal_eval(value)
                    return parsed if isinstance(parsed, list) else [parsed]
                except (ValueError, SyntaxError):
                    return [value]
            else:
                return [value] if value is not None else None
        else:
            # Default to string or passthrough
            return value
    
    outputs = {}  # {instance_alias: {param_key: value}}

    def _extract_nested(value: Any, nested_key: str):
        if not nested_key:
            return value, True
        current = value
        for part in str(nested_key).split('.'):
            if isinstance(current, dict) and part in current:
                current = current[part]
            else:
                return None, False
        return current, True

